import os, glob, shutil, datetime
from playwright.sync_api import sync_playwright
pw_pass = [l.split('=',1)[1].strip() for l in open(r'zetaris-platform\.env') if l.startswith('ZETARIS_ADMIN_PASSWORD=')][0]
Q = open(r'sql\04_federated.sql', encoding='utf-8-sig').read()
# first statement only (Q1)
q1 = Q.split(';')[0].strip() + ';'
print(q1[:200])
with sync_playwright() as p:
    b = p.chromium.launch(channel="chrome", headless=True)
    c0 = b.new_context(viewport={"width":1920,"height":1080})
    pg = c0.new_page()
    pg.goto("http://localhost:3000/login", wait_until="networkidle")
    pg.fill("input[type=text]", "admin@zetaris.com"); pg.fill("input[type=password]", pw_pass); pg.click("text=Sign In")
    pg.wait_for_timeout(5000)
    c0.storage_state(path="ui/_state.json"); c0.close()
    os.makedirs("ui/video", exist_ok=True)
    ctx = b.new_context(viewport={"width":1920,"height":1080}, storage_state="ui/_state.json",
                        record_video_dir="ui/video", record_video_size={"width":1920,"height":1080})
    pg = ctx.new_page()
    pg.goto("http://localhost:3000/", wait_until="networkidle"); pg.wait_for_timeout(2500)
    pg.screenshot(path="ui/10_home.png")
    pg.click("text=Database"); pg.wait_for_timeout(1500)
    pg.screenshot(path="ui/11_tree.png")
    pg.click("text=Workbench"); pg.wait_for_timeout(1000)
    pg.click("text=SQL Workspace"); pg.wait_for_timeout(2500)
    pg.click("text=New Query"); pg.wait_for_timeout(3000)
    pg.click(".monaco-editor"); pg.keyboard.press("Control+A"); pg.keyboard.press("Delete")
    pg.keyboard.insert_text(q1); pg.wait_for_timeout(1500)
    pg.screenshot(path="ui/12_query_typed.png")
    pg.keyboard.press("Control+Enter")
    pg.wait_for_timeout(15000)
    pg.screenshot(path="ui/13_query_result.png")
    body = pg.inner_text("body")
    open("ui/result_body.txt","w",encoding="utf-8").write(body)
    print("TS", datetime.datetime.now().isoformat())
    ctx.close(); b.close()
v = glob.glob("ui/video/*.webm")
print(v)
if v: shutil.copy(v[0], "ui/zetaris_ui_federated_query.webm")
